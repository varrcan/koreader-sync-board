// Генерация src/schema.d.ts из api/openapi.yaml. Node API вместо CLI ради transform:
// CLI отображает `format: binary` в string, а тело импорта статистики — файл (Blob).
import fs from "node:fs";
import openapiTS, { astToString } from "openapi-typescript";
import ts from "typescript";

const BLOB = ts.factory.createTypeReferenceNode(ts.factory.createIdentifier("Blob"));
const NULL = ts.factory.createLiteralTypeNode(ts.factory.createNull());

const ast = await openapiTS(new URL("../../../api/openapi.yaml", import.meta.url), {
  transform(schemaObject) {
    if (schemaObject.format === "binary") {
      return schemaObject.nullable ? ts.factory.createUnionTypeNode([BLOB, NULL]) : BLOB;
    }
  },
});

const header = `/**
 * This file was auto-generated by openapi-typescript.
 * Do not make direct changes to the file.
 */

`;
fs.writeFileSync(new URL("../src/schema.d.ts", import.meta.url), header + astToString(ast));
